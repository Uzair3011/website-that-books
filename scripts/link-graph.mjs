// Writes docs/seo/link-graph.md from the rendered pages: for every indexable
// page, its body links in and out with their anchor text, its click depth
// from the homepage, and the flags `npm run seo:check` enforces.
// Run with `npm run seo:links` after changing links.
import { writeFileSync } from "node:fs";
import {
  BODY_INBOUND_EXEMPT,
  LIMITS,
  clickDepth,
  loadSite,
  runChecks,
} from "./seo-check.mjs";

const site = loadSite();
const { analyses, graph } = runChecks(site);
const depth = clickDepth(site, analyses);
const resolve = (path) => site.resolveRedirect(path) ?? path;
const cell = (text) => text.replace(/\|/g, "\\|");

// Body links between indexable pages, with anchor text.
const indexable = site.pages.map((page) => page.path);
const outbound = new Map(indexable.map((path) => [path, []]));
const inbound = new Map(indexable.map((path) => [path, []]));
for (const from of indexable)
  for (const anchor of analyses.get(from).anchors) {
    const to = resolve(anchor.href);
    if (to === from) continue;
    const link = { from, to, text: anchor.text || "(no text)", kind: anchor.kind };
    outbound.get(from).push(link);
    inbound.get(to)?.push(link);
  }

const flagsOf = (path) => {
  const flags = [];
  const into = graph.inMain.get(path)?.size ?? 0;
  if (into < LIMITS.contextualLinks)
    flags.push(BODY_INBOUND_EXEMPT.has(path) ? `under ${LIMITS.contextualLinks} body links in (exempt)` : `under ${LIMITS.contextualLinks} body links in`);
  if (depth.get(path) > LIMITS.maxClickDepth) flags.push(`more than ${LIMITS.maxClickDepth} clicks deep`);
  return flags;
};

const rows = indexable.map((path) => {
  const flags = flagsOf(path);
  return `| \`${path}\` | ${graph.inMain.get(path)?.size ?? 0} | ${new Set(outbound.get(path).map((l) => l.to)).size} | ${depth.get(path)} | ${flags.join("; ") || "none"} |`;
});
const flagged = indexable.filter((path) => flagsOf(path).length);

const list = (links, side) =>
  links.length
    ? links.map((l) => `- \`${side === "in" ? l.from : l.to}\`: “${cell(l.text)}”${l.kind === "inline" ? "" : ` (${l.kind})`}`).join("\n")
    : "- none";

const sections = indexable.map(
  (path) => `### \`${path}\`

Clicks from the homepage: ${depth.get(path)}. Body links in from ${graph.inMain.get(path)?.size ?? 0} pages.

**Inbound (${inbound.get(path).length} links)**

${list(inbound.get(path), "in")}

**Outbound (${outbound.get(path).length} links)**

${list(outbound.get(path), "out")}`,
);

const markdown = `# Internal link graph

Generated by \`npm run seo:links\` from the rendered pages (\`scripts/link-graph.mjs\`). Do not edit by hand; re-run it after changing links.

**What counts.** Only links in a page's own content: \`<main>\` without the breadcrumb. The header, footer and breadcrumb link to almost everything, so they are left out. They do count for click depth, because a visitor or crawler can follow them. Links from the 404 and checkout pages are not counted.

**Link kinds.** A link with no label in brackets is in-sentence body copy. *card* is a related-links card, *button* a button, *styled* a standalone text or price link, *form* a link inside a form.

**Rules** (enforced by \`npm run seo:check\`): no orphan pages; at least ${LIMITS.contextualLinks} other pages link to each page from their body, except ${[...BODY_INBOUND_EXEMPT].map((p) => `\`${p}\``).join(", ")}; no page more than ${LIMITS.maxClickDepth} clicks from the homepage; no vague anchors ("click here", "here", "read more" and the like); no in-sentence anchor used more than ${LIMITS.maxAnchorRepeats} times across the site; and the required links in \`LINK_RULES\` in \`scripts/seo-check.mjs\`.

## Summary

| Page | Body links in (pages) | Body links out (pages) | Clicks from home | Flags |
|---|---|---|---|---|
${rows.join("\n")}

## Flagged pages

${flagged.length ? flagged.map((path) => `- \`${path}\`: ${flagsOf(path).join("; ")}`).join("\n") : "None."}

## Every page

${sections.join("\n\n")}
`;

writeFileSync(new URL("../docs/seo/link-graph.md", import.meta.url), markdown);
console.log(`Wrote docs/seo/link-graph.md: ${indexable.length} pages, ${flagged.length} flagged.`);
